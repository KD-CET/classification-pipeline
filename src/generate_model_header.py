"""Part 3 -- code generation: surfaces.npz + scaling bounds -> model.h

Reads the per-class peak-normalised maps (surfaces.npz, written by
kde_class_contours.py), the TRAINING scaling bounds, and the cluster names
(cluster_names.json, written by score_dbscan.py), and emits a C header the
ESP32 sketch includes.

Feature space (the firmware must compute exactly this before scaling):
    x = UV (filtered ADC reading, 0-4095)
    y = log10(1 + IR) (filtered TSL2591 IR channel)

Run from inside src/:   python generate_model_header.py
Writes:                 ../firmware/inference/model.h
"""
import json
from pathlib import Path

import numpy as np
from pipeline_common import load_split_scaled, quantize, GRID_N, REJECT_TAU

OUT = Path("../firmware/inference/model.h")

surfaces = np.load("surfaces.npz")
classes = sorted(int(k[1:]) for k in surfaces.files)        # cluster ids, in order
names = json.load(open("cluster_names.json"))                # id -> lighting name
K, G = len(classes), GRID_N

# The shipped table: [class][row = y = log IR][col = x = UV], one byte per cell.
# Same quantize() and same row/col convention as cell_of() in pipeline_common.
table = np.stack([quantize(surfaces[f"c{c}"]) for c in classes])
assert table.dtype == np.uint8 and table.shape == (K, G, G)

lo, hi = load_split_scaled()["bounds"]                       # TRAINING bounds
bounds = np.array([lo[0], hi[0], lo[1], hi[1]], dtype=np.float32)
assert bounds[1] > bounds[0] and bounds[3] > bounds[2]

class_names = [names[str(c)] for c in classes]

# ---- footprint check: K * G^2 bytes of table + 16 bytes of bounds
table_bytes = table.nbytes
bounds_bytes = bounds.nbytes
assert table_bytes == K * G * G, (table_bytes, K * G * G)
assert bounds_bytes == 16, bounds_bytes
print(f"classes (table order): {class_names}")
print(f"CLASS_TABLE : {table_bytes} B  = K*G^2 = {K}*{G}^2")
print(f"SCALE_BOUNDS: {bounds_bytes} B  = 4 floats")
print(f"predicted model footprint: {table_bytes + bounds_bytes} B")


# ---- emit the header
def c_float(v):
    s = f"{float(v):.9g}"            # 9 significant digits round-trips a float32
    if not any(ch in s for ch in ".eEn"):
        s += ".0"                    # "0f" is not valid C; "0.0f" is
    return s + "f"


lines = [
    "// model.h -- GENERATED by src/generate_model_header.py. Do not edit by hand.",
    "// Re-run the generator after retraining.",
    "//",
    "// Features (compute exactly this on the device before scaling):",
    "//   x = UV            filtered GUVA-S12SD ADC reading (0-4095)",
    "//   y = log10(1 + IR) filtered TSL2591 IR channel (0-65535)",
    "// Scale:  sx = (x - SCALE_BOUNDS[0]) / (SCALE_BOUNDS[1] - SCALE_BOUNDS[0])",
    "//         sy = (y - SCALE_BOUNDS[2]) / (SCALE_BOUNDS[3] - SCALE_BOUNDS[2])",
    "// Cell:   col = (int)(sx * GRID_N), row = (int)(sy * GRID_N), clipped to [0, GRID_N-1]",
    "// Table:  CLASS_TABLE[class][row][col] / 255.0  -> argmax, UNKNOWN if below REJECT_TAU",
    f"// Footprint: table {table_bytes} B (K*G^2 = {K}*{G}^2) + bounds {bounds_bytes} B",
    "",
    "#pragma once",
    "#include <stdint.h>",
    "#if defined(ARDUINO)",
    "#include <pgmspace.h>",
    "#endif",
    "#ifndef PROGMEM",
    "#define PROGMEM",
    "#endif",
    "",
    f"#define GRID_N {G}",
    f"#define NUM_CLASSES {K}",
    f"#define REJECT_TAU {c_float(REJECT_TAU)}",
    "",
    "const uint8_t CLASS_TABLE[NUM_CLASSES][GRID_N][GRID_N] PROGMEM = {",
]
for k, c in enumerate(classes):
    lines.append(f"  {{ // class {k}: {class_names[k]} (DBSCAN cluster {c})")
    for r in range(G):
        row = ", ".join(f"{v:3d}" for v in table[k, r])
        lines.append(f"    {{{row}}},  // row {r}")
    lines.append("  },")
lines += [
    "};",
    "",
    "// xmin, xmax, ymin, ymax  (x = UV, y = log10(1 + IR)), from the TRAINING split",
    "const float SCALE_BOUNDS[4] = {" + ", ".join(c_float(b) for b in bounds) + "};",
    "",
    "const char* CLASS_NAMES[NUM_CLASSES] = {"
    + ", ".join(f'"{n}"' for n in class_names) + "};",
    "",
]

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines))
print(f"wrote {OUT}")